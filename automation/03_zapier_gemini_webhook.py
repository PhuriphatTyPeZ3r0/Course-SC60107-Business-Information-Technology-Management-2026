def simulate_zapier_webhook_payload(user_feedback: str, timestamp_str: str = "2026-10-01 09:30:00"):
    print(f"[*] Simulating incoming Zapier Webhook from https://idex-dusky.vercel.app/ ...")
    print(f"    Raw Feedback: {user_feedback}")
    
    # Simulate Gemini Sentiment Analysis
    # Rule-based fallback if no live API key
    lower_text = user_feedback.lower()
    if any(w in lower_text for w in ["ช้า", "ค้าง", "พัง", "ไม่ดี", "error", "bug", "แย่", "fail", "broken"]):
        sentiment = "Negative"
        category = "Bug"
    elif any(w in lower_text for w in ["ดี", "ชอบ", "เยี่ยม", "good", "fast", "great"]):
        sentiment = "Positive"
        category = "General"
    else:
        sentiment = "Neutral"
        category = "Feature Request"

    analysis_result = f"Sentiment: {sentiment}\nCategory: {category}\nFeedback: {user_feedback}"
    print(f"[+] AI Analysis Result:\n{analysis_result}\n")
    
    if sentiment == "Negative":
        email_html = HTML_EMAIL_TEMPLATE.format(
            raw_feedback=user_feedback,
            ai_analysis=analysis_result.replace('\n', '<br/>'),
            timestamp=timestamp_str
        )
        print("[!] Negative Sentiment Detected -> Triggering Zapier Email Action!")
        return {
            "status": "alert_dispatched",
            "sentiment": sentiment,
            "category": category,
            "email_html": email_html
        }
    else:
        print("[i] Non-negative feedback -> Logging to database.")
        return {
            "status": "logged",
            "sentiment": sentiment,
            "category": category,
            "email_html": None
        }

